def _has_list_answer_language(text):
    """
    Return True only when the transcript contains language
    that actually presents or classifies items.

    This is deliberately different from simply checking
    whether the word "types" appears.

    Example rejected:

        "What are the different types?"

    Example accepted:

        "There are three types of AI..."

        "AI is classified into three categories..."

        "The types include supervised and unsupervised..."
    """

    text_lower = str(
        text or ""
    ).lower()

    positive_patterns = [
        r"\bthere\s+are\b",
        r"\bthere\s+is\b",
        r"\btypes?\s+(?:are|include|includes)\b",
        r"\bkinds?\s+(?:are|include|includes)\b",
        r"\bcategories?\s+(?:are|include|includes)\b",
        r"\bsubsets?\s+(?:are|include|includes)\b",
        r"\bclassified\s+into\b",
        r"\bclassifies\s+into\b",
        r"\bdivided\s+into\b",
        r"\bdivide\s+into\b",
        r"\bconsists\s+of\b",
        r"\bclassification\s+of\b",
        r"\bclassification\s+includes\b",
        r"\bcan\s+be\s+classified\b",
        r"\bcan\s+be\s+divided\b",
        r"\binclude[s]?\b",
    ]

    return any(
        re.search(
            pattern,
            text_lower,
        )
        for pattern in positive_patterns
    )


def _is_list_introduction(text):
    """
    Detect transcript sentences that introduce a list/topic
    without actually giving the list.

    These should NOT be used as answers.
    """

    text_lower = str(
        text or ""
    ).lower()

    introduction_patterns = [
        r"\bwe\s+are\s+going\s+to\s+cover\b",
        r"\bwe\s+will\s+cover\b",
        r"\bwe\s+are\s+going\s+to\s+discuss\b",
        r"\bwe\s+will\s+discuss\b",
        r"\bwe\s+are\s+going\s+to\s+learn\b",
        r"\bwe\s+will\s+learn\b",
        r"\btoday\s+we\s+are\s+going\s+to\b",
        r"\btoday\s+we\s+will\b",
        r"\bwhat\s+are\s+the\s+different\s+types\b",
        r"\bwhat\s+are\s+the\s+types\b",
        r"\bwhat\s+are\s+the\s+different\s+subsets\b",
        r"\bwhat\s+are\s+the\s+subsets\b",
        r"\bwe\s+are\s+going\s+to\s+look\s+at\b",
        r"\bwe\s+will\s+look\s+at\b",
        r"\bin\s+this\s+session\s+we\s+will\b",
        r"\bin\s+today's\s+session\s+we\s+will\b",
    ]

    return any(
        re.search(
            pattern,
            text_lower,
        )
        for pattern in introduction_patterns
    )


def _list_topic_score(
    topic,
    text,
):
    """
    Measure how strongly the requested list topic appears
    in the transcript.
    """

    if not topic:
        return 0.0

    keyword_score = _keyword_score(
        topic,
        text,
    )

    phrase_score = _phrase_score(
        topic,
        text,
    )

    return max(
        keyword_score,
        phrase_score,
    )


# =========================================================
# EVIDENCE VALIDATION
# =========================================================

def _validate_evidence(
    question,
    sources,
):
    """
    Validate retrieved evidence before allowing it to reach
    answer generation.

    Retrieval asks:

        "Could this chunk be relevant?"

    Validation asks:

        "Does this chunk provide enough actual transcript
         evidence to answer this question?"

    This is deterministic and does NOT call Qwen.
    """

    if not sources:
        return []

    normalized_question = _normalize_question(
        question
    )

    qtype = _detect_question_type(
        normalized_question
    )

    validated = []

    # -----------------------------------------------------
    # Definition topic
    # -----------------------------------------------------

    definition_topic = ""

    if qtype == "definition":
        definition_topic = _extract_question_topic(
            normalized_question
        )

    # -----------------------------------------------------
    # List topic
    # -----------------------------------------------------

    list_topic = ""

    if qtype == "list":
        list_topic = _extract_list_topic(
            normalized_question
        )

    # -----------------------------------------------------
    # Location topic
    # -----------------------------------------------------

    location_topic = ""

    if qtype == "location":
        location_topic = _extract_location_topic(
            normalized_question
        )

    # -----------------------------------------------------
    # Validate every candidate
    # -----------------------------------------------------

    for item in sources:
        row = item["row"]

        text = str(
            row.get("text", "")
        ).strip()

        title = str(
            row.get("title", "")
        ).strip()

        if not text:
            continue

        vector_score = float(
            item.get(
                "vector_score",
                0.0,
            )
        )

        keyword_score = _keyword_score(
            normalized_question,
            text,
        )

        exact_score = _exact_keyword_score(
            normalized_question,
            text,
        )

        phrase_score = _phrase_score(
            normalized_question,
            text,
        )

        text_support = _text_evidence_score(
            normalized_question,
            text,
        )

        # -------------------------------------------------
        # General evidence confidence
        # -------------------------------------------------

        evidence_score = (
            0.65 * vector_score
            + 0.35 * text_support
        )

        accepted = False

        # -------------------------------------------------
        # Definition validation
        # -------------------------------------------------

        if qtype == "definition":
            if definition_topic:
                topic_score = _keyword_score(
                    definition_topic,
                    text,
                )

                topic_phrase_score = _phrase_score(
                    definition_topic,
                    text,
                )

                best_definition_score = 0.0

                for sentence in _split_sentences(
                    text
                ):
                    sentence_score = (
                        _score_definition_sentence(
                            definition_topic,
                            sentence,
                        )
                    )

                    if (
                        sentence_score
                        > best_definition_score
                    ):
                        best_definition_score = (
                            sentence_score
                        )

                # A lecture does not always define a concept with
                # dictionary wording such as "X is a ...". It may
                # explain the concept across several sentences.
                # Strong semantic retrieval plus an explicit topic
                # occurrence is sufficient for Qwen to synthesize
                # a grounded definition from the transcript.
                strong_topic_evidence = (
                    (
                        topic_phrase_score >= 1.0
                        or topic_score >= 0.80
                    )
                    and vector_score >= 0.55
                )

                dictionary_definition = (
                    best_definition_score
                    >= DEFINITION_MIN_SENTENCE_SCORE
                    and (
                        topic_score
                        >= DEFINITION_MIN_TOPIC_SCORE
                        or topic_phrase_score >= 1.0
                    )
                    and vector_score >= 0.35
                )

                accepted = (
                    strong_topic_evidence
                    or dictionary_definition
                )

                evidence_score = max(
                    0.55 * vector_score
                    + 0.30 * topic_score
                    + 0.15 * best_definition_score,
                    0.65 * vector_score
                    + 0.35 * topic_score,
                )

        # -------------------------------------------------
        # List / classification validation
        # -------------------------------------------------

        elif qtype == "list":
            topic_score = _list_topic_score(
                list_topic,
                text,
            )

            has_list_language = (
                _has_list_answer_language(
                    text
                )
            )

            is_introduction = (
                _is_list_introduction(
                    text
                )
            )

            # -------------------------------------------------
            # IMPORTANT:
            #
            # "What are the different types?"
            # "We are going to cover the different types..."
            #
            # are NOT actual answers.
            # -------------------------------------------------

            accepted = (
                topic_score
                >= LIST_MIN_TOPIC_SCORE
                and has_list_language
                and not is_introduction
                and vector_score
                >= LIST_MIN_VECTOR_SCORE
            )

            evidence_score = (
                0.40 * vector_score
                + 0.40 * topic_score
                + 0.20 * (
                    1.0
                    if has_list_language
                    else 0.0
                )
            )

        # -------------------------------------------------
        # Location validation
        # -------------------------------------------------

        elif qtype == "location":
            if location_topic:
                topic_text_score = _keyword_score(
                    location_topic,
                    text,
                )

                topic_phrase_score = _phrase_score(
                    location_topic,
                    text,
                )

                accepted = (
                    topic_text_score >= 0.40
                    or topic_phrase_score >= 1.0
                )

                evidence_score = (
                    0.45 * vector_score
                    + 0.35 * topic_text_score
                    + 0.20 * topic_phrase_score
                )

            else:
                accepted = (
                    vector_score >= EVIDENCE_MIN_VECTOR
                    and text_support
                    >= EVIDENCE_MIN_TEXT_SUPPORT
                )

        # -------------------------------------------------
        # General / how-to / comparison / example / overview
        # -------------------------------------------------

        else:
            accepted = (
                evidence_score >= EVIDENCE_MIN_SCORE
                and (
                    vector_score >= EVIDENCE_MIN_VECTOR
                    or text_support
                    >= EVIDENCE_MIN_TEXT_SUPPORT
                )
            )

        if accepted:
            validated_item = dict(item)

            validated_item[
                "evidence_score"
            ] = min(
                1.0,
                float(evidence_score),
            )

            validated_item[
                "validated_keyword_score"
            ] = keyword_score

            validated_item[
                "validated_exact_score"
            ] = exact_score

            validated_item[
                "validated_phrase_score"
            ] = phrase_score

            validated.append(
                validated_item
            )

    # -----------------------------------------------------
    # Sort validated evidence
    # -----------------------------------------------------

    validated.sort(
        key=lambda item: (
            float(
                item.get(
                    "evidence_score",
                    0.0,
                )
            ),
            float(
                item.get(
                    "score",
                    0.0,
                )
            ),
        ),
        reverse=True,
    )

    # -----------------------------------------------------
    # Debug validation
    # -----------------------------------------------------

    print(
        f"[RAG] Evidence validation: "
        f"{len(sources)} candidates -> "
        f"{len(validated)} validated"
    )

    for rank, item in enumerate(
        validated[:5],
        start=1,
    ):
        row = item["row"]

        print(
            "[RAG] VALIDATED "
            f"#{rank} "
            f"evidence={item.get('evidence_score', 0):.3f} "
            f"retrieval={item.get('score', 0):.3f} "
            f"vector={item.get('vector_score', 0):.3f} "
            f"keyword={item.get('validated_keyword_score', 0):.3f} "
            f"video={row['video_id']} "
            f"title={row['title']} "
            f"time={row['start']:.2f}-{row['end']:.2f}"
        )

    if not validated:
        print(
            "[RAG] Evidence validation rejected all "
            "retrieved candidates."
        )

    return validated


# =========================================================
# TIMESTAMP
# =========================================================

def _format_timestamp(seconds):
    try:
        seconds = max(
            0,
            int(float(seconds)),
        )
    except Exception:
        seconds = 0

    hours = seconds // 3600

    minutes = (
        seconds % 3600
    ) // 60

    secs = seconds % 60

    if hours > 0:
        return (
            f"{hours}:{minutes:02d}:{secs:02d}"
        )

    return (
        f"{minutes}:{secs:02d}"
    )


