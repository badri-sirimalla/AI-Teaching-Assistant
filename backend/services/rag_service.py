def _definition_answer_is_valid(
    question,
    answer,
):
    """Reject obvious off-topic or meta answers from the generator."""

    answer = str(
        answer or ""
    ).strip()

    if not answer:
        return False

    if answer == NOT_FOUND_MESSAGE:
        return False

    topic = _extract_question_topic(
        question
    )

    if topic and (
        _phrase_score(
            topic,
            answer,
        ) < 1.0
        and _keyword_score(
            topic,
            answer,
        ) < 0.40
    ):
        return False

    lower = answer.lower()

    forbidden_meta = [
        "based on the transcript",
        "according to the transcript",
        "the transcript",
        "lecture transcript",
        "transcript 1",
        "transcript 2",
        "transcript 3",
        "the evidence",
        "retrieval",
        "embedding",
    ]

    if any(
        phrase in lower
        for phrase in forbidden_meta
    ):
        return False

    return True


