# =========================================================
# RESULT
# =========================================================

def _result(
    answer,
    sources,
):
    references = []

    for item in sources:
        references.append(
            _source_dict(item)
        )

    result = {
        "answer": answer,
        "sources": references,
        "references": references,
    }

    # -----------------------------------------------------
    # Include strongest video information for frontend.
    # -----------------------------------------------------

    if references:
        strongest = references[0]

        result["video"] = {
            "video_id": strongest["video_id"],
            "number": strongest["number"],
            "title": strongest["title"],
            "start": strongest["start"],
            "end": strongest["end"],
            "start_timestamp": strongest[
                "start_timestamp"
            ],
            "end_timestamp": strongest[
                "end_timestamp"
            ],
        }

        result["video_id"] = strongest[
            "video_id"
        ]

    else:
        result["video"] = None
        result["video_id"] = None

    return result


