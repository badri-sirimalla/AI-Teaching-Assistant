# =========================================================
# RETRIEVAL
# =========================================================

def _retrieve(
    question,
    video_id=None,
):
    started = time.perf_counter()

    df = load_embeddings_df()

    if (
        df is None
        or df.empty
    ):
        return []

    with INDEX_LOCK:
        matrix = (
            None
            if EMBEDDING_MATRIX is None
            else EMBEDDING_MATRIX.copy()
        )

        working_df = df.copy()

    if (
        matrix is None
        or matrix.size == 0
    ):
        return []

    ready_ids = _get_ready_video_ids()

    if not ready_ids:
        return []

    # -----------------------------------------------------
    # Only READY videos
    # -----------------------------------------------------

    mask = (
        working_df["video_id"]
        .astype(str)
        .isin(ready_ids)
    )

    # -----------------------------------------------------
    # Optional selected video
    # -----------------------------------------------------

    if video_id is not None:
        mask = (
            mask
            & (
                working_df["video_id"]
                .astype(str)
                == str(video_id)
            )
        )

    candidate_df = (
        working_df.loc[mask]
        .reset_index(drop=True)
    )

    if candidate_df.empty:
        return []

    candidate_indices = (
        working_df.index[mask].to_numpy()
    )

    candidate_matrix = matrix[
        candidate_indices
    ]

    # -----------------------------------------------------
    # Normalize query
    # -----------------------------------------------------

    normalized_question = _normalize_question(
        question
    )

    # -----------------------------------------------------
    # Query embedding
    # -----------------------------------------------------

    embedding_started = time.perf_counter()

    query_embedding = (
        ollama_service.create_embedding(
            normalized_question
        )
    )

    embedding_elapsed = (
        time.perf_counter()
        - embedding_started
    )

    if not query_embedding:
        return []

    query_vector = np.asarray(
        query_embedding[0],
        dtype=np.float32,
    ).reshape(1, -1)

    # -----------------------------------------------------
    # Vector similarity
    # -----------------------------------------------------

    similarity_started = time.perf_counter()

    similarities = cosine_similarity(
        query_vector,
        candidate_matrix,
    )[0]

    similarity_elapsed = (
        time.perf_counter()
        - similarity_started
    )

    # -----------------------------------------------------
    # Calculate scores
    # -----------------------------------------------------

    scores = []

    for index, row in candidate_df.iterrows():
        vector_score = float(
            similarities[index]
        )

        keyword_score = _keyword_score(
            normalized_question,
            row["text"],
        )

        exact_keyword_score = (
            _exact_keyword_score(
                normalized_question,
                row["text"],
            )
        )

        title_score = _title_score(
            normalized_question,
            row["title"],
        )

        phrase_score = _phrase_score(
            normalized_question,
            row["text"],
        )

        question_type_score = (
            _question_type_score(
                normalized_question,
                row["text"],
                row["title"],
            )
        )

        # -------------------------------------------------
        # Final reranking score
        # -------------------------------------------------

        final_score = (
            0.50 * vector_score
            + 0.20 * keyword_score
            + 0.18 * exact_keyword_score
            + 0.07 * title_score
            + 0.05 * question_type_score
        )

        # Strong phrase match should matter.
        if phrase_score > 0:
            final_score += 0.08

        final_score = min(
            final_score,
            1.0,
        )

        scores.append(
            {
                "row": row,
                "vector_score": vector_score,
                "keyword_score": keyword_score,
                "exact_keyword_score": exact_keyword_score,
                "title_score": title_score,
                "phrase_score": phrase_score,
                "question_type_score": question_type_score,
                "score": final_score,
            }
        )

    # -----------------------------------------------------
    # Sort
    # -----------------------------------------------------

    scores.sort(
        key=lambda item: item["score"],
        reverse=True,
    )

    # -----------------------------------------------------
    # Adaptive threshold
    # -----------------------------------------------------

    configured_threshold = float(
        getattr(
            Config,
            "SIMILARITY_THRESHOLD",
            0.55,
        )
    )

    qtype = _detect_question_type(
        normalized_question
    )

    selected = []

    for item in scores:
        score = item["score"]
        vector_score = item["vector_score"]
        keyword_score = item["keyword_score"]
        phrase_score = item["phrase_score"]

        accepted = False

        if score >= configured_threshold:
            accepted = True

        # Exact topic matches deserve a chance even when
        # vector similarity is slightly lower.
        if phrase_score >= 1.0:
            if vector_score >= 0.30:
                accepted = True

        # Definition questions can use strong lexical
        # evidence because definitions are often short.
        if qtype == "definition":
            if (
                vector_score >= 0.40
                and keyword_score >= 0.50
            ):
                accepted = True

        # List questions need reasonable semantic support.
        if qtype == "list":
            if (
                vector_score >= 0.40
                and keyword_score >= 0.50
            ):
                accepted = True

        if accepted:
            selected.append(item)

    # -----------------------------------------------------
    # Fallback
    #
    # Validation below makes the final decision.
    # -----------------------------------------------------

    if not selected and scores:
        best = scores[0]

        if (
            best["vector_score"] >= 0.40
            or best["keyword_score"] >= 0.50
            or best["phrase_score"] >= 1.0
        ):
            selected = [best]

    # -----------------------------------------------------
    # Return top candidates
    # -----------------------------------------------------

    max_candidates = max(
        int(
            getattr(
                Config,
                "TOP_K",
                3,
            )
        ) * 4,
        8,
    )

    selected = selected[
        :max_candidates
    ]

    print(
        f"[RAG] Retrieval: "
        f"{len(candidate_df)} candidates, "
        f"{len(selected)} selected, "
        f"embedding={embedding_elapsed:.3f}s, "
        f"similarity={similarity_elapsed:.3f}s, "
        f"total={time.perf_counter() - started:.3f}s"
    )

    # -----------------------------------------------------
    # Debug top results
    # -----------------------------------------------------

    for rank, item in enumerate(
        selected[:5],
        start=1,
    ):
        row = item["row"]

        print(
            "[RAG] "
            f"#{rank} "
            f"score={item['score']:.3f} "
            f"vector={item['vector_score']:.3f} "
            f"keyword={item['keyword_score']:.3f} "
            f"exact={item['exact_keyword_score']:.3f} "
            f"title={item['title_score']:.3f} "
            f"video={row['video_id']} "
            f"title={row['title']} "
            f"time={row['start']:.2f}-{row['end']:.2f}"
        )

    return selected


# =========================================================
# MERGE ADJACENT SOURCES
# =========================================================

def _merge_adjacent_sources(
    sources,
):
    if not sources:
        return []

    ordered = sorted(
        sources,
        key=lambda item: (
            str(
                item["row"]["video_id"]
            ),
            float(
                item["row"]["start"]
            ),
        ),
    )

    merged = []

    for item in ordered:
        row = item["row"]

        if not merged:
            merged.append(
                {
                    **item,
                    "row": row.copy(),
                }
            )
            continue

        previous = merged[-1]["row"]

        same_video = (
            str(
                previous["video_id"]
            )
            == str(
                row["video_id"]
            )
        )

        previous_end = float(
            previous["end"]
        )

        current_start = float(
            row["start"]
        )

        # Merge chunks that are very close together.
        if (
            same_video
            and current_start
            <= previous_end + 2.0
        ):
            previous["end"] = max(
                previous_end,
                float(row["end"]),
            )

            previous_text = str(
                previous["text"]
            ).strip()

            current_text = str(
                row["text"]
            ).strip()

            if current_text not in previous_text:
                previous["text"] = (
                    previous_text
                    + " "
                    + current_text
                ).strip()

            # Keep the best retrieval score.
            if (
                item["score"]
                > merged[-1]["score"]
            ):
                for key in [
                    "score",
                    "vector_score",
                    "keyword_score",
                    "exact_keyword_score",
                    "title_score",
                    "phrase_score",
                    "question_type_score",
                ]:
                    merged[-1][key] = item[key]

        else:
            merged.append(
                {
                    **item,
                    "row": row.copy(),
                }
            )

    # Sort by retrieval relevance again.
    merged.sort(
        key=lambda item: item["score"],
        reverse=True,
    )

    return merged


