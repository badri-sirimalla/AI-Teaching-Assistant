def load_embeddings_df(force_reload=False):
    """
    Load embeddings.joblib into memory.

    The dataframe and embedding matrix are cached so the
    embeddings file is not loaded for every question.
    """

    global EMBEDDINGS_DF
    global EMBEDDING_MATRIX

    if EMBEDDINGS_DF is not None and not force_reload:
        return EMBEDDINGS_DF

    with INDEX_LOCK:
        if EMBEDDINGS_DF is not None and not force_reload:
            return EMBEDDINGS_DF

        path = Config.EMBEDDINGS_PATH

        try:
            data = joblib.load(path)

        except FileNotFoundError:
            print(
                f"[RAG] Embeddings file not found: {path}"
            )

            EMBEDDINGS_DF = pd.DataFrame(
                columns=EMBEDDING_COLUMNS
            )

            EMBEDDING_MATRIX = np.empty(
                (0, 0),
                dtype=np.float32,
            )

            return EMBEDDINGS_DF

        except Exception as exc:
            print(
                f"[RAG] Could not load embeddings: {exc}"
            )
            raise

        # -------------------------------------------------
        # Convert loaded object to DataFrame
        # -------------------------------------------------

        if isinstance(data, pd.DataFrame):
            df = data.copy()

        elif isinstance(data, dict):
            df = pd.DataFrame(data)

        elif isinstance(data, list):
            df = pd.DataFrame(data)

        else:
            raise ValueError(
                "Unsupported embeddings.joblib format."
            )

        # -------------------------------------------------
        # Validate columns
        # -------------------------------------------------

        missing = [
            column
            for column in EMBEDDING_COLUMNS
            if column not in df.columns
        ]

        if missing:
            raise ValueError(
                "embeddings.joblib is missing required "
                f"columns: {missing}"
            )

        # -------------------------------------------------
        # Normalize dataframe
        # -------------------------------------------------

        df["video_id"] = (
            df["video_id"]
            .fillna("")
            .astype(str)
        )

        df["title"] = (
            df["title"]
            .fillna("")
            .astype(str)
        )

        df["text"] = (
            df["text"]
            .fillna("")
            .astype(str)
        )

        df["chunk_id"] = (
            df["chunk_id"]
            .fillna("")
            .astype(str)
        )

        df["number"] = (
            df["number"]
            .fillna("")
            .astype(str)
        )

        df["start"] = pd.to_numeric(
            df["start"],
            errors="coerce",
        ).fillna(0.0)

        df["end"] = pd.to_numeric(
            df["end"],
            errors="coerce",
        ).fillna(0.0)

        # -------------------------------------------------
        # Build embedding matrix
        # -------------------------------------------------

        vectors = []
        valid_rows = []

        for index, value in df["embedding"].items():
            try:
                vector = np.asarray(
                    value,
                    dtype=np.float32,
                )

                if vector.ndim != 1:
                    continue

                if vector.size == 0:
                    continue

                if not np.all(np.isfinite(vector)):
                    continue

                vectors.append(vector)
                valid_rows.append(index)

            except Exception:
                continue

        if len(valid_rows) != len(df):
            df = (
                df.loc[valid_rows]
                .reset_index(drop=True)
            )

        if vectors:
            dimensions = {
                vector.shape[0]
                for vector in vectors
            }

            if len(dimensions) != 1:
                raise ValueError(
                    "Embeddings have inconsistent dimensions."
                )

            EMBEDDING_MATRIX = np.vstack(
                vectors
            ).astype(np.float32)

        else:
            EMBEDDING_MATRIX = np.empty(
                (0, 0),
                dtype=np.float32,
            )

        EMBEDDINGS_DF = (
            df.reset_index(drop=True)
        )

        print(
            f"[RAG] Loaded {len(EMBEDDINGS_DF)} "
            "embedding chunks."
        )

        return EMBEDDINGS_DF


# =========================================================
# REBUILD EMBEDDING MATRIX
# =========================================================

def _rebuild_embedding_matrix():
    global EMBEDDING_MATRIX

    if (
        EMBEDDINGS_DF is None
        or EMBEDDINGS_DF.empty
    ):
        EMBEDDING_MATRIX = np.empty(
            (0, 0),
            dtype=np.float32,
        )
        return

    vectors = []

    for value in EMBEDDINGS_DF["embedding"]:
        vector = np.asarray(
            value,
            dtype=np.float32,
        )

        if vector.ndim != 1:
            raise ValueError(
                "Invalid embedding dimension."
            )

        if vector.size == 0:
            raise ValueError(
                "Empty embedding found."
            )

        vectors.append(vector)

    dimensions = {
        vector.shape[0]
        for vector in vectors
    }

    if len(dimensions) != 1:
        raise ValueError(
            "Embeddings have inconsistent dimensions."
        )

    EMBEDDING_MATRIX = np.vstack(
        vectors
    ).astype(np.float32)


# =========================================================
# SAVE INDEX
# =========================================================

def _save_embeddings():
    global EMBEDDINGS_DF

    if EMBEDDINGS_DF is None:
        return

    joblib.dump(
        EMBEDDINGS_DF,
        Config.EMBEDDINGS_PATH,
    )


