# TOKENIZATION
# =========================================================

def _raw_tokens(text):
    if not text:
        return []

    return re.findall(
        r"[a-zA-Z0-9]+(?:['-][a-zA-Z0-9]+)*",
        str(text).lower(),
    )


def _tokenize(text):
    tokens = _raw_tokens(text)

    return [
        token
        for token in tokens
        if token not in STOP_WORDS
        and len(token) > 1
    ]


# =========================================================
# KEYWORD SCORE
# =========================================================

def _keyword_score(
    question,
    text,
):
    question_tokens = set(
        _tokenize(question)
    )

    text_tokens = set(
        _tokenize(text)
    )

    if not question_tokens:
        return 0.0

    if not text_tokens:
        return 0.0

    overlap = (
        question_tokens
        & text_tokens
    )

    return (
        len(overlap)
        / len(question_tokens)
    )


# =========================================================
# EXACT KEYWORD SCORE
# =========================================================

def _exact_keyword_score(
    question,
    text,
):
    question = str(
        question or ""
    ).lower()

    text = str(
        text or ""
    ).lower()

    if not question or not text:
        return 0.0

    question_tokens = _tokenize(
        question
    )

    if not question_tokens:
        return 0.0

    score = 0.0

    meaningful_phrase = " ".join(
        question_tokens
    )

    if (
        len(question_tokens) >= 2
        and meaningful_phrase in text
    ):
        score += 0.75

    text_tokens = set(
        _raw_tokens(text)
    )

    matched = sum(
        1
        for token in question_tokens
        if token in text_tokens
    )

    token_ratio = (
        matched
        / len(question_tokens)
    )

    score += (
        0.25
        * token_ratio
    )

    return min(
        score,
        1.0,
    )


# =========================================================
# TITLE SCORE
# =========================================================

def _title_score(
    question,
    title,
):
    question_tokens = set(
        _tokenize(question)
    )

    title_tokens = set(
        _tokenize(title)
    )

    if not question_tokens:
        return 0.0

    if not title_tokens:
        return 0.0

    overlap = (
        question_tokens
        & title_tokens
    )

    score = (
        len(overlap)
        / len(question_tokens)
    )

    question_text = " ".join(
        _tokenize(question)
    )

    title_text = " ".join(
        _tokenize(title)
    )

    if (
        len(question_text.split()) >= 2
        and question_text in title_text
    ):
        score = max(
            score,
            1.0,
        )

    return min(
        score,
        1.0,
    )


# =========================================================
# EXACT PHRASE SCORE
# =========================================================

def _phrase_score(
    question,
    text,
):
    question_tokens = _tokenize(
        question
    )

    if len(question_tokens) < 2:
        return 0.0

    phrase = " ".join(
        question_tokens
    )

    normalized_text = re.sub(
        r"\s+",
        " ",
        str(text).lower(),
    )

    if phrase in normalized_text:
        return 1.0

    return 0.0


# =========================================================
# QUESTION TYPE
# =========================================================

def _detect_question_type(question):
    text = str(
        question or ""
    ).lower().strip()

    # -----------------------------------------------------
    # Location / lecture lookup
    # -----------------------------------------------------

    location_patterns = [
        r"^where\s+",
        r"^which\s+video",
        r"^what\s+video",
        r"^in\s+which\s+video",
        r"^where\s+is",
        r"^where\s+was",
        r"^where\s+are",
        r"^where\s+were",
    ]

    for pattern in location_patterns:
        if re.search(
            pattern,
            text,
        ):
            return "location"

    # -----------------------------------------------------
    # Definition
    # -----------------------------------------------------

    definition_patterns = [
        r"^what\s+is\s+",
        r"^what\s+are\s+",
        r"^who\s+is\s+",
        r"^what\s+does\s+.+\s+mean",
        r"^define\s+",
        r"^definition\s+of\s+",
        r"^meaning\s+of\s+",
        r"^what\s+is\s+the\s+meaning\s+of\s+",
    ]

    for pattern in definition_patterns:
        if re.search(
            pattern,
            text,
        ):
            return "definition"

    # -----------------------------------------------------
    # Comparison
    # -----------------------------------------------------

    if (
        "difference between" in text
        or "differences between" in text
        or "compare" in text
        or "comparison between" in text
        or "versus" in text
        or " vs " in f" {text} "
    ):
        return "comparison"

    # -----------------------------------------------------
    # How-to
    # -----------------------------------------------------

    if (
        text.startswith("how ")
        or "how to " in text
        or "steps to " in text
        or "procedure for " in text
    ):
        return "how_to"

    # -----------------------------------------------------
    # Example
    # -----------------------------------------------------

    if (
        "example" in text
        or "examples" in text
        or "give an example" in text
    ):
        return "example"

    # -----------------------------------------------------
    # Overview
    # -----------------------------------------------------

    if (
        "what is this video about" in text
        or "what does this video cover" in text
        or "summarize" in text
        or "summary" in text
        or "overview" in text
    ):
        return "overview"

    # -----------------------------------------------------
    # List / classification
    #
    # This is intentionally checked after definition.
    # For example:
    #
    # "What are the types of AI?"
    #
    # should be treated as a list question rather than
    # a generic "what are" definition question.
    # -----------------------------------------------------

    list_patterns = [
        r"^what\s+are\s+the\s+types\s+of\s+",
        r"^what\s+are\s+the\s+kinds\s+of\s+",
        r"^what\s+are\s+the\s+categories\s+of\s+",
        r"^what\s+are\s+the\s+subsets\s+of\s+",
        r"^types\s+of\s+",
        r"^kinds\s+of\s+",
        r"^categories\s+of\s+",
        r"^subsets\s+of\s+",
    ]

    for pattern in list_patterns:
        if re.search(
            pattern,
            text,
        ):
            return "list"

    return "general"


# =========================================================
# QUESTION TOPIC EXTRACTION
# =========================================================

def _extract_question_topic(question):
    text = _normalize_question(
        question
    )

    patterns = [
        r"^what\s+is\s+(.+?)$",
        r"^what\s+are\s+(.+?)$",
        r"^define\s+(.+?)$",
        r"^definition\s+of\s+(.+?)$",
        r"^meaning\s+of\s+(.+?)$",
        r"^what\s+does\s+(.+?)\s+mean$",
        r"^who\s+is\s+(.+?)$",
    ]

    for pattern in patterns:
        match = re.match(
            pattern,
            text,
            flags=re.IGNORECASE,
        )

        if match:
            topic = match.group(1).strip()

            topic = re.sub(
                r"[?.!]+$",
                "",
                topic,
            ).strip()

            return topic

    return ""


# =========================================================
# LIST TOPIC EXTRACTION
# =========================================================

def _extract_list_topic(question):
    """
    Extract the topic from list/classification questions.

    Examples:

        What are the types of artificial intelligence?
        -> artificial intelligence

        Types of machine learning
        -> machine learning
    """

    text = _normalize_question(
        question
    )

    patterns = [
        r"^what\s+are\s+the\s+types\s+of\s+(.+?)$",
        r"^what\s+are\s+the\s+kinds\s+of\s+(.+?)$",
        r"^what\s+are\s+the\s+categories\s+of\s+(.+?)$",
        r"^what\s+are\s+the\s+subsets\s+of\s+(.+?)$",
        r"^types\s+of\s+(.+?)$",
        r"^kinds\s+of\s+(.+?)$",
        r"^categories\s+of\s+(.+?)$",
        r"^subsets\s+of\s+(.+?)$",
    ]

    for pattern in patterns:
        match = re.match(
            pattern,
            text,
            flags=re.IGNORECASE,
        )

        if match:
            return match.group(1).strip()

    return ""


# =========================================================
# QUESTION TYPE SCORE
# =========================================================

def _question_type_score(
    question,
    text,
    title,
):
    qtype = _detect_question_type(
        question
    )

    text_lower = str(
        text or ""
    ).lower()

    title_lower = str(
        title or ""
    ).lower()

    score = 0.0

    if qtype == "definition":
        definition_terms = [
            " is ",
            " are ",
            " means ",
            " refers to ",
            " defined as ",
            " known as ",
            " called ",
            " is a ",
            " is an ",
            " stands for ",
            " branch of ",
        ]

        if any(
            term in f" {text_lower} "
            for term in definition_terms
        ):
            score += 0.8

        if (
            "definition" in text_lower
            or "define" in text_lower
        ):
            score += 0.2

    elif qtype == "list":
        list_terms = [
            "there are",
            "types are",
            "types include",
            "classified into",
            "divided into",
            "categories include",
            "kinds include",
            "consists of",
            "classification",
        ]

        if any(
            term in text_lower
            for term in list_terms
        ):
            score = 1.0

        elif any(
            term in text_lower
            for term in [
                "first",
                "second",
                "third",
                "one type",
                "another type",
            ]
        ):
            score = 0.6

    elif qtype == "location":
        if title_lower:
            score += 0.5

        if text_lower:
            score += 0.5

    elif qtype == "how_to":
        how_terms = [
            "step",
            "first",
            "then",
            "next",
            "finally",
            "process",
            "procedure",
            "create",
            "install",
            "use",
        ]

        if any(
            term in text_lower
            for term in how_terms
        ):
            score = 1.0

    elif qtype == "comparison":
        comparison_terms = [
            "difference",
            "different",
            "whereas",
            "while",
            "compared",
            "versus",
            "both",
        ]

        if any(
            term in text_lower
            for term in comparison_terms
        ):
            score = 1.0

    elif qtype == "example":
        example_terms = [
            "example",
            "for example",
            "such as",
            "instance",
        ]

        if any(
            term in text_lower
            for term in example_terms
        ):
            score = 1.0

    elif qtype == "overview":
        if title_lower:
            score += 0.4

        if len(text_lower) > 100:
            score += 0.6

    return min(
        score,
        1.0,
    )


