def add_chunks_to_index(chunks):
    """
    Embed and add transcript chunks to the RAG index.

    Existing chunks belonging to the same video are removed
    before the new chunks are inserted.
    """

    global EMBEDDINGS_DF

    if not chunks:
        return

    valid_chunks = []

    for chunk in chunks:
        text = str(
            chunk.get("text", "")
        ).strip()

        if not text:
            continue

        video_id = chunk.get("video_id")

        if video_id is None:
            continue

        try:
            start = float(
                chunk.get("start", 0)
            )
        except Exception:
            start = 0.0

        try:
            end = float(
                chunk.get("end", 0)
            )
        except Exception:
            end = start

        valid_chunks.append(
            {
                "video_id": str(video_id),
                "number": str(
                    chunk.get("number", "")
                ),
                "title": str(
                    chunk.get("title", "")
                ),
                "start": start,
                "end": end,
                "text": text,
                "chunk_id": str(
                    chunk.get(
                        "chunk_id",
                        f"{video_id}_{start}",
                    )
                ),
            }
        )

    if not valid_chunks:
        return

    texts = [
        chunk["text"]
        for chunk in valid_chunks
    ]

    print(
        f"[RAG] Creating embeddings for "
        f"{len(texts)} chunks..."
    )

    started = time.perf_counter()

    embeddings = ollama_service.create_embedding(
        texts
    )

    elapsed = (
        time.perf_counter()
        - started
    )

    if len(embeddings) != len(valid_chunks):
        raise ValueError(
            "Ollama returned a different number "
            "of embeddings than requested."
        )

    rows = []

    for chunk, embedding in zip(
        valid_chunks,
        embeddings,
    ):
        row = dict(chunk)
        row["embedding"] = embedding
        rows.append(row)

    new_df = pd.DataFrame(
        rows,
        columns=EMBEDDING_COLUMNS,
    )

    with INDEX_LOCK:
        if EMBEDDINGS_DF is None:
            load_embeddings_df()

        if EMBEDDINGS_DF is None:
            EMBEDDINGS_DF = pd.DataFrame(
                columns=EMBEDDING_COLUMNS
            )

        video_ids = set(
            new_df["video_id"]
            .astype(str)
        )

        # Remove old chunks from this video.
        if not EMBEDDINGS_DF.empty:
            EMBEDDINGS_DF = (
                EMBEDDINGS_DF[
                    ~EMBEDDINGS_DF[
                        "video_id"
                    ]
                    .astype(str)
                    .isin(video_ids)
                ]
                .reset_index(drop=True)
            )

        EMBEDDINGS_DF = pd.concat(
            [
                EMBEDDINGS_DF,
                new_df,
            ],
            ignore_index=True,
        )

        _rebuild_embedding_matrix()
        _save_embeddings()

    print(
        f"[RAG] Added {len(new_df)} chunks "
        f"in {elapsed:.2f}s."
    )

    # Return the number of chunks actually added so the
    # processing pipeline can report the correct count.
    return len(new_df)


