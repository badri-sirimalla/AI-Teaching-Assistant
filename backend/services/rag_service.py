# DEFINITION ANSWER
# =========================================================

def _definition_answer(
    question,
    sources,
):
    """
    Return the lecture's own definition wording.

    Definition questions should not be paraphrased by the LLM when
    the transcript already contains a direct explanation. We select
    the strongest definition sentence and, when the immediately
    following sentence clearly continues that definition, preserve it
    too. This keeps the answer faithful to the lecture wording.
    """

    topic = _extract_question_topic(
        question
    )

    if not topic:
        return None

    candidates = []

    for item in sources:
        row = item["row"]

        text = str(
            row.get("text", "")
        ).strip()

        if not text:
            continue

        sentences = _split_sentences(
            text
        )

        if not sentences:
            sentences = [text]

        for sentence_index, sentence in enumerate(
            sentences
        ):
            score = _score_definition_sentence(
                topic,
                sentence,
            )

            # A lecture may explain a concept without using an
            # explicit dictionary phrase. Reward a direct topic
            # sentence that contains an explanatory action.
            phrase_score = _phrase_score(
                topic,
                sentence,
            )

            keyword_score = _keyword_score(
                topic,
                sentence,
            )

            if phrase_score >= 1.0:
                score += 0.08

            if keyword_score >= 0.75:
                score += 0.04

            candidates.append(
                {
                    "sentence": sentence,
                    "sentence_index": sentence_index,
                    "sentences": sentences,
                    "score": min(score, 1.0),
                    "source": item,
                }
            )

    if not candidates:
        return None

    candidates.sort(
        key=lambda item: item["score"],
        reverse=True,
    )

    best = candidates[0]

    if (
        best["score"]
        < DEFINITION_MIN_SENTENCE_SCORE
    ):
        return None

    first_sentence = _extract_definition_from_sentence(
        topic,
        best["sentence"],
    )

    if not first_sentence:
        return None

    answer_sentences = [
        first_sentence
    ]

    # Preserve one immediately following sentence when it clearly
    # continues the definition, e.g. "It uses an agent...".
    next_index = (
        best["sentence_index"] + 1
    )

    sentences = best["sentences"]

    if next_index < len(sentences):
        next_sentence = str(
            sentences[next_index]
        ).strip()

        next_lower = next_sentence.lower()

        topic_overlap = _keyword_score(
            topic,
            next_sentence,
        )

        continuation = (
            topic_overlap >= 0.40
            or next_lower.startswith((
                "it ",
                "this ",
                "these ",
                "they ",
                "the agent ",
                "the environment ",
            ))
        )

        if continuation:
            answer_sentences.append(
                next_sentence
            )

    answer = " ".join(
        answer_sentences
    ).strip()

    meaningful_tokens = _tokenize(
        answer
    )

    if len(meaningful_tokens) < 3:
        return None

    print(
        "[RAG] Exact definition extracted: "
        f"{answer}"
    )

    return (
        answer,
        best["source"],
    )


