# EVIDENCE TEXT SCORE
# =========================================================

def _text_evidence_score(
    question,
    text,
):
    """
    Measure how strongly the actual transcript text supports
    the question.

    Title relevance is intentionally excluded.
    """

    keyword_score = _keyword_score(
        question,
        text,
    )

    exact_score = _exact_keyword_score(
        question,
        text,
    )

    phrase_score = _phrase_score(
        question,
        text,
    )

    return min(
        1.0,
        (
            0.50 * keyword_score
            + 0.30 * exact_score
            + 0.20 * phrase_score
        ),
    )


