def _source_dict(item):
    row = item["row"]

    return {
        "video_id": str(
            row["video_id"]
        ),

        "number": str(
            row.get("number", "")
        ),

        "title": str(
            row.get("title", "")
        ),

        "start": float(
            row.get("start", 0)
        ),

        "end": float(
            row.get("end", 0)
        ),

        "start_timestamp": _format_timestamp(
            row.get("start", 0)
        ),

        "end_timestamp": _format_timestamp(
            row.get("end", 0)
        ),

        "text": str(
            row.get("text", "")
        ).strip(),

        "score": round(
            float(
                item.get(
                    "score",
                    0,
                )
            ),
            4,
        ),

        "evidence_score": round(
            float(
                item.get(
                    "evidence_score",
                    item.get(
                        "score",
                        0,
                    ),
                )
            ),
            4,
        ),
    }


# =========================================================
# ANSWER CLEANING
# =========================================================

def _clean_answer(answer):
    if answer is None:
        return ""

    text = str(answer).strip()

    # -----------------------------------------------------
    # Remove Qwen thinking blocks
    # -----------------------------------------------------

    text = re.sub(
        r"<think>.*?</think>",
        "",
        text,
        flags=re.IGNORECASE | re.DOTALL,
    )

    text = re.sub(
        r"<thinking>.*?</thinking>",
        "",
        text,
        flags=re.IGNORECASE | re.DOTALL,
    )

    # -----------------------------------------------------
    # Remove answer wrappers
    # -----------------------------------------------------

    text = re.sub(
        r"</?answer>",
        "",
        text,
        flags=re.IGNORECASE,
    )

    # -----------------------------------------------------
    # Remove reference section
    # -----------------------------------------------------

    text = re.split(
        r"\n\s*(?:###\s*)?referenced in\s*:?\s*",
        text,
        flags=re.IGNORECASE,
    )[0]

    text = re.split(
        r"\n\s*(?:###\s*)?sources?\s*:?\s*",
        text,
        flags=re.IGNORECASE,
    )[0]

    # -----------------------------------------------------
    # Remove common reasoning/meta lines
    # -----------------------------------------------------

    reasoning_prefixes = (
        "okay, so",
        "ok, so",
        "hmm,",
        "the user",
        "the question",
        "we are given",
        "we need to",
        "we have to",
        "i need to",
        "i have to",
        "i should",
        "i must",
        "let me",
        "let's",
        "looking at",
        "according to the instructions",
        "according to the course material",
        "course material provided",
        "the evidence provided",
        "answer should",
        "i will answer",
        "we must",
        "we should",
        "first,",
        "first we",
        "therefore,",
        "thus,",
    )

    cleaned_lines = []

    for line in text.splitlines():
        stripped = line.strip()

        if not stripped:
            continue

        lower = stripped.lower()

        if any(
            lower.startswith(prefix)
            for prefix in reasoning_prefixes
        ):
            continue

        if (
            lower.startswith("###")
            or lower.startswith("reasoning:")
            or lower.startswith("analysis:")
        ):
            continue

        cleaned_lines.append(
            stripped
        )

    text = "\n".join(
        cleaned_lines
    ).strip()

    # -----------------------------------------------------
    # Remove unnecessary bullets
    # -----------------------------------------------------

    text = re.sub(
        r"^\s*[-*]\s+",
        "",
        text,
        flags=re.MULTILINE,
    )

    # -----------------------------------------------------
    # Remove excessive whitespace
    # -----------------------------------------------------

    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text,
    )

    return text.strip()


# =========================================================
# DEFINITION SENTENCE SPLITTER
# =========================================================

def _split_sentences(text):
    text = str(
        text or ""
    ).strip()

    if not text:
        return []

    parts = re.split(
        r"(?<=[.!?])\s+",
        text,
    )

    result = []

    for part in parts:
        part = part.strip()

        if not part:
            continue

        result.append(part)

    return result


# =========================================================
# DEFINITION SENTENCE SCORING
# =========================================================

def _score_definition_sentence(
    topic,
    sentence,
):
    """
    Score a sentence as a possible definition.

    IMPORTANT:

    A topic mention alone is NOT considered a definition.

    Example:

        "Artificial intelligence every single day."

    is rejected.

    Example:

        "Machine learning is a branch of computer science..."

    is accepted.
    """

    topic_tokens = set(
        _tokenize(topic)
    )

    sentence_tokens = set(
        _tokenize(sentence)
    )

    if not topic_tokens:
        return 0.0

    if not sentence_tokens:
        return 0.0

    overlap = (
        topic_tokens
        & sentence_tokens
    )

    topic_overlap = (
        len(overlap)
        / len(topic_tokens)
    )

    lower = sentence.lower()

    # -----------------------------------------------------
    # A definition MUST contain an actual definition
    # pattern.
    # -----------------------------------------------------

    definition_patterns = [
        r"\bis\s+(?:a|an|the)\b",
        r"\bare\s+(?:a|an|the)\b",
        r"\bmeans\b",
        r"\brefers\s+to\b",
        r"\bis\s+defined\s+as\b",
        r"\bare\s+defined\s+as\b",
        r"\bknown\s+as\b",
        r"\bis\s+called\b",
        r"\bis\s+known\s+as\b",
        r"\bstands\s+for\b",
        r"\bbranch\s+of\b",
        r"\bis\s+the\s+process\b",
        r"\bis\s+a\s+process\b",
        r"\bis\s+an\s+approach\b",
        r"\bis\s+a\s+method\b",
        r"\bis\s+a\s+technique\b",
        # Lecture definitions are often phrased as actions rather
        # than dictionary-style "X is ..." sentences.
        r"\btrains\s+(?:a|an|the)\b",
        r"\buses\s+(?:a|an|the)\b",
        r"\buses\s+.+\bto\b",
        r"\binvolves\b",
        r"\bconsists\s+of\b",
        r"\bhelps\b",
    ]

    has_definition_pattern = any(
        re.search(
            pattern,
            lower,
        )
        for pattern in definition_patterns
    )

    # -----------------------------------------------------
    # Topic must actually be present.
    # -----------------------------------------------------

    if topic_overlap < 0.75:
        return 0.0

    # -----------------------------------------------------
    # Topic mention without definition = reject.
    # -----------------------------------------------------

    if not has_definition_pattern:
        return 0.0

    # -----------------------------------------------------
    # Strong definition evidence.
    # -----------------------------------------------------

    score = (
        0.55 * topic_overlap
        + 0.45
    )

    # -----------------------------------------------------
    # Prefer exact topic phrase.
    # -----------------------------------------------------

    topic_phrase = " ".join(
        _raw_tokens(topic)
    )

    normalized_sentence = " ".join(
        _raw_tokens(sentence)
    )

    if (
        topic_phrase
        and topic_phrase in normalized_sentence
    ):
        score += 0.10

    # -----------------------------------------------------
    # Penalize obvious conversational filler.
    # -----------------------------------------------------

    filler_patterns = [
        "hey guys",
        "hello guys",
        "today in this video",
        "in this video we are going to",
        "let us learn",
        "we are going to learn",
    ]

    for filler in filler_patterns:
        if filler in lower:
            score -= 0.08
            break

    return min(
        max(score, 0.0),
        1.0,
    )


# =========================================================
# EXTRACT CLEAN DEFINITION
# =========================================================

def _extract_definition_from_sentence(
    topic,
    sentence,
):
    sentence = str(
        sentence or ""
    ).strip()

    topic = str(
        topic or ""
    ).strip()

    if not sentence or not topic:
        return ""

    topic_words = _raw_tokens(
        topic
    )

    if not topic_words:
        return sentence

    topic_pattern = (
        r"\b"
        + r"\s+".join(
            re.escape(word)
            for word in topic_words
        )
        + r"\b"
    )

    match = re.search(
        topic_pattern,
        sentence,
        flags=re.IGNORECASE,
    )

    if match:
        extracted = sentence[
            match.start():
        ].strip()

    else:
        extracted = sentence

    # -----------------------------------------------------
    # Remove common introductory phrases
    # -----------------------------------------------------

    extracted = re.sub(
        r"^(?:today|in this video|in today's video)"
        r"(?:\s+we\s+(?:are|will)\s+going\s+to)?"
        r"\s+(?:learn|discuss|understand)\s+",
        "",
        extracted,
        flags=re.IGNORECASE,
    ).strip()

    # -----------------------------------------------------
    # Fix a few common Whisper artifacts
    # -----------------------------------------------------

    replacements = [
        (
            r"\bthe using of\b",
            "using",
        ),
        (
            r"\busing of data\b",
            "using data",
        ),
        (
            r"\buses of data\b",
            "uses data",
        ),
    ]

    for pattern, replacement in replacements:
        extracted = re.sub(
            pattern,
            replacement,
            extracted,
            flags=re.IGNORECASE,
        )

    # -----------------------------------------------------
    # Remove leading punctuation
    # -----------------------------------------------------

    extracted = re.sub(
        r"^[,;:\-*\s]+",
        "",
        extracted,
    ).strip()

    # -----------------------------------------------------
    # Make first character readable
    # -----------------------------------------------------

    if extracted:
        extracted = (
            extracted[0].upper()
            + extracted[1:]
        )

    return extracted


