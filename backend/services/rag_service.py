# LOCATION TOPIC EXTRACTION
# =========================================================

def _extract_location_topic(question):
    text = _normalize_question(
        question
    )

    patterns = [
        r"^where\s+is\s+(.+?)\s+taught$",
        r"^where\s+is\s+(.+?)\s+covered$",
        r"^where\s+is\s+(.+?)\s+discussed$",
        r"^which\s+video\s+teaches\s+(.+?)$",
        r"^in\s+which\s+video\s+is\s+(.+?)\s+taught$",
        r"^in\s+which\s+video\s+is\s+(.+?)\s+covered$",
    ]

    for pattern in patterns:
        match = re.match(
            pattern,
            text,
            flags=re.IGNORECASE,
        )

        if match:
            return match.group(1).strip()

    return ""


# =========================================================
# LOCATION ANSWER
# =========================================================

def _build_location_answer(
    question,
    sources,
):
    if not sources:
        return ""

    topic = _extract_location_topic(
        question
    )

    # -----------------------------------------------------
    # Simple "which video"
    # -----------------------------------------------------

    if not topic:
        if _normalize_question(
            question
        ) == "which video":

            row = sources[0]["row"]

            return (
                f'The relevant video is '
                f'"{row["title"]}".'
            )

        row = sources[0]["row"]

        return (
            f"This video covers the topic "
            f"discussed around "
            f"{_format_timestamp(row['start'])}."
        )

    # -----------------------------------------------------
    # Rank source videos by topic evidence
    # -----------------------------------------------------

    grouped = {}

    for item in sources:
        row = item["row"]

        video_id = str(
            row["video_id"]
        )

        text = str(
            row.get("text", "")
        )

        title = str(
            row.get("title", "")
        )

        text_score = _keyword_score(
            topic,
            text,
        )

        title_score = _title_score(
            topic,
            title,
        )

        phrase_score = _phrase_score(
            topic,
            text,
        )

        total = (
            0.55 * text_score
            + 0.25 * title_score
            + 0.20 * phrase_score
            + 0.20 * float(
                item.get(
                    "evidence_score",
                    item.get(
                        "score",
                        0,
                    ),
                )
            )
        )

        if video_id not in grouped:
            grouped[video_id] = {
                "video_id": video_id,
                "title": title,
                "number": str(
                    row.get("number", "")
                ),
                "score": total,
                "start": float(
                    row.get("start", 0)
                ),
                "end": float(
                    row.get("end", 0)
                ),
            }

        else:
            existing = grouped[
                video_id
            ]

            if total > existing["score"]:
                existing["score"] = total
                existing["start"] = float(
                    row.get("start", 0)
                )
                existing["end"] = float(
                    row.get("end", 0)
                )

    if not grouped:
        return ""

    ranked = sorted(
        grouped.values(),
        key=lambda item: item["score"],
        reverse=True,
    )

    best = ranked[0]

    # -----------------------------------------------------
    # Make sure topic exists in transcript evidence.
    # -----------------------------------------------------

    evidence_match = False

    for item in sources:
        row = item["row"]

        if str(
            row["video_id"]
        ) != best["video_id"]:
            continue

        text = str(
            row.get("text", "")
        )

        if (
            _keyword_score(
                topic,
                text,
            ) >= 0.40
            or _phrase_score(
                topic,
                text,
            ) >= 1.0
        ):
            evidence_match = True
            break

    if not evidence_match:
        return ""

    return (
        f"{best['title']} "
        f"({_format_timestamp(best['start'])}–"
        f"{_format_timestamp(best['end'])})"
    )


# =========================================================
# DEFINITION EVIDENCE SELECTION
# =========================================================

def _select_definition_sources(
    question,
    sources,
):
    """
    Select a very small, focused transcript excerpt for a
    definition question.

    Retrieval is intentionally broad, but definition generation
    should not receive several unrelated chunks. The best sentence
    is selected first and then given a small amount of local context.
    """

    topic = _extract_question_topic(
        question
    )

    if not topic or not sources:
        return sources[:1]

    candidates = []

    for source_index, item in enumerate(
        sources
    ):
        row = item["row"]
        text = str(
            row.get("text", "")
        ).strip()

        if not text:
            continue

        sentences = _split_sentences(
            text
        )

        if not sentences:
            sentences = [text]

        for sentence_index, sentence in enumerate(
            sentences
        ):
            sentence = str(
                sentence or ""
            ).strip()

            if not sentence:
                continue

            definition_score = _score_definition_sentence(
                topic,
                sentence,
            )

            phrase_score = _phrase_score(
                topic,
                sentence,
            )

            keyword_score = _keyword_score(
                topic,
                sentence,
            )

            retrieval_score = float(
                item.get(
                    "evidence_score",
                    item.get(
                        "score",
                        0,
                    ),
                )
            )

            total = (
                0.50 * definition_score
                + 0.25 * phrase_score
                + 0.15 * keyword_score
                + 0.10 * retrieval_score
            )

            candidates.append(
                {
                    "score": total,
                    "source_index": source_index,
                    "sentence_index": sentence_index,
                    "sentences": sentences,
                    "item": item,
                }
            )

    if not candidates:
        return sources[:1]

    candidates.sort(
        key=lambda item: item["score"],
        reverse=True,
    )

    best = candidates[0]
    sentences = best["sentences"]
    center = best["sentence_index"]

    # Keep only a tiny local window around the strongest sentence.
    start = max(
        0,
        center - 1,
    )
    end = min(
        len(sentences),
        center + 2,
    )

    excerpt = " ".join(
        str(sentence).strip()
        for sentence in sentences[start:end]
        if str(sentence).strip()
    ).strip()

    selected = dict(
        best["item"]
    )

    selected_row = dict(
        selected["row"]
    )
    selected_row["text"] = excerpt
    selected["row"] = selected_row

    print(
        "[RAG] Definition focus: "
        f"source={best['source_index'] + 1} "
        f"sentence={best['sentence_index'] + 1} "
        f"score={best['score']:.3f}"
    )

    return [selected]


