# REMOVE VIDEO
# =========================================================

def remove_video_from_index(video_id):
    """
    Remove all chunks belonging to a video.
    """

    global EMBEDDINGS_DF

    if video_id is None:
        return

    target_id = str(video_id)

    with INDEX_LOCK:
        if EMBEDDINGS_DF is None:
            load_embeddings_df()

        if (
            EMBEDDINGS_DF is None
            or EMBEDDINGS_DF.empty
        ):
            return

        before = len(
            EMBEDDINGS_DF
        )

        EMBEDDINGS_DF = (
            EMBEDDINGS_DF[
                EMBEDDINGS_DF[
                    "video_id"
                ]
                .astype(str)
                != target_id
            ]
            .reset_index(drop=True)
        )

        removed = (
            before
            - len(EMBEDDINGS_DF)
        )

        _rebuild_embedding_matrix()
        _save_embeddings()

    print(
        f"[RAG] Removed {removed} chunks "
        f"for video {target_id}."
    )


# =========================================================
# QUESTION NORMALIZATION
# =========================================================

def _normalize_question(question):
    """
    Normalize natural-language questions.
    """

    text = str(
        question or ""
    ).strip()

    text = re.sub(
        r"\s+",
        " ",
        text,
    )

    text = text.lower()

    # -----------------------------------------------------
    # Contractions
    # -----------------------------------------------------

    text = text.replace(
        "what's",
        "what is",
    )

    text = text.replace(
        "where's",
        "where is",
    )

    # -----------------------------------------------------
    # Remove trailing punctuation
    # -----------------------------------------------------

    text = re.sub(
        r"[?!]+$",
        "",
        text,
    ).strip()

    # -----------------------------------------------------
    # Topic expansion
    # -----------------------------------------------------

    words = text.split()

    expanded_words = []

    for word in words:
        cleaned = re.sub(
            r"[^\w-]",
            "",
            word,
        )

        if cleaned in TOPIC_EXPANSIONS:
            expanded_words.extend(
                TOPIC_EXPANSIONS[
                    cleaned
                ].split()
            )
        else:
            expanded_words.append(
                word
            )

    text = " ".join(
        expanded_words
    )

    # -----------------------------------------------------
    # "where X taught"
    # -----------------------------------------------------

    text = re.sub(
        r"^where\s+(.+?)\s+taught$",
        r"where is \1 taught",
        text,
        flags=re.IGNORECASE,
    )

    # -----------------------------------------------------
    # "where X covered"
    # -----------------------------------------------------

    text = re.sub(
        r"^where\s+(.+?)\s+covered$",
        r"where is \1 covered",
        text,
        flags=re.IGNORECASE,
    )

    # -----------------------------------------------------
    # "where X discussed"
    # -----------------------------------------------------

    text = re.sub(
        r"^where\s+(.+?)\s+discussed$",
        r"where is \1 discussed",
        text,
        flags=re.IGNORECASE,
    )

    # -----------------------------------------------------
    # "what video teaches X"
    # -----------------------------------------------------

    match = re.match(
        r"^what\s+video\s+"
        r"(?:teaches|teach|taught)\s+"
        r"(.+?)$",
        text,
        flags=re.IGNORECASE,
    )

    if match:
        topic = match.group(1).strip()

        return (
            f"which video teaches {topic}"
        )

    # -----------------------------------------------------
    # "what video taught us"
    # -----------------------------------------------------

    if re.fullmatch(
        r"what\s+video\s+"
        r"(?:taught|teaches|teach)\s+"
        r"(?:us|me)",
        text,
        flags=re.IGNORECASE,
    ):
        return (
            "what is taught in this video"
        )

    # -----------------------------------------------------
    # "what is this video about"
    # -----------------------------------------------------

    if re.fullmatch(
        r"what\s+(?:is|was)\s+"
        r"(?:this\s+)?video\s+about",
        text,
        flags=re.IGNORECASE,
    ):
        return (
            "what is this video about"
        )

    # -----------------------------------------------------
    # "which video"
    # -----------------------------------------------------

    if re.fullmatch(
        r"which\s+video",
        text,
        flags=re.IGNORECASE,
    ):
        return "which video"

    return text


